export function createSeed(): AdminSettingsWorkspaceState {
  const products: Product[] = [],
    variants: Variant[] = [],
    inventoryBalances: Balance[] = [],
    images: ProductImage[] = [];
  const locations = Array.from({ length: 8 }, (_, i) => ({
    id: `loc-${i + 1}`,
    rack: i < 4 ? "A" : "B",
    shelf: String((i % 2) + 1),
    box: String(i + 1),
    active: true,
  }));
  definitions.forEach(
    (
      [
        name,
        departmentId,
        categoryId,
        fabric,
        sleeve,
        collar,
        colours,
        sizes,
        price,
      ],
      i,
    ) => {
      const id = `product-${i + 1}`;
      products.push({
        id,
        designCode: `TF-${String(i + 1).padStart(3, "0")}`,
        name,
        departmentId,
        categoryId,
        fabric,
        sleeve,
        collar,
        fit: "Regular",
        pattern: "Solid",
        status: "active",
        defaultPricePaise: price * 100,
        costPricePaise: Math.round(price * 55),
        description: `A fictional ${fabric.toLowerCase()} ${categoryId.toLowerCase()} for the demo collection. Colour and size availability are tracked separately.`,
        createdAt: "2026-11-01T10:00:00Z",
      });
      const image = ["Jeans", "Pants"].includes(categoryId)
        ? "trousers"
        : ["Dress", "Kurti", "Kurta", "Saree"].includes(categoryId)
          ? "dress"
          : ["Socks", "Handkerchief", "Belt", "Cap"].includes(categoryId)
            ? "accessories"
            : "shirt";
      images.push({
        productId: id,
        angle: "front",
        kind: "placeholder",
        srcOrAssetKey: `/images/${image}-${i % 4}.svg`,
        label: "Illustrative placeholder — not a product photograph",
      });
      colours.forEach((colour, ci) =>
        sizes.forEach((size, si) => {
          const variantId = `variant-${i + 1}-${ci}-${si}`;
          variants.push({
            id: variantId,
            productId: id,
            sku: `TF${String(i + 1).padStart(3, "0")}-${ci + 1}-${size}`,
            colour,
            sizeCode: size,
            sizeSystem: sizes[0].includes("Y")
              ? "age"
              : /^\d+$/.test(sizes[0])
                ? "numeric"
                : "letter",
            packUnit: name.includes("3 Pair")
              ? "3-pair pack"
              : name.includes("3 Pack")
                ? "3-piece pack"
                : categoryId === "Socks"
                  ? "pair"
                  : "piece",
            status: "active",
          });
          inventoryBalances.push({
            variantId,
            locationId: locations[i % 8].id,
            onHand:
              i === 0 && ci === 0 && size === "XL" ? 3 : (i + ci + si) % 8,
            nonSellable: 0,
          });
          if (i === 0 && ci === 0 && size === "XL")
            inventoryBalances.push({
              variantId,
              locationId: "loc-5",
              onHand: 4,
              nonSellable: 0,
            });
        }),
      );
    },
  );
  return {
    schemaVersion: 1,
    revision: 0,
    products,
    variants,
    inventoryBalances,
    images,
    locations,
    departments: [...new Set(products.map((p) => p.departmentId))],
    categories: [...new Set(products.map((p) => p.categoryId))],
    sessions: [],
    shortlistItems: [],
    pickItems: [],
    returnToBoxTasks: [],
    draftBills: [],
    sales: [],
    payments: [],
    saleReturns: [],
    stockMovements: [],
    settings: {
      shopName: "Thread & Form",
      taxPercent: 0,
      lowStockThreshold: 2,
      timeZone: "Asia/Kolkata",
    },
    activeSessionId: null,
  };
}
